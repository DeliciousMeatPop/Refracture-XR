#!/usr/bin/env python3
"""Writes modules.cmake (one OBJECT library per Digitalis Soong module) from soong_modules.json.

soong_modules.json comes from tools/soong_modules.py, run in the WSL AOSP tree after a Digitalis
build. Each module keeps Soong's include order and defines (several modules see the same header
names in different generated directories). Linux-only files are left out; src/*.cpp replaces them.

    python tools/gen_modules_cmake.py tools/soong_modules.json modules.cmake
"""
import json
import re
import sys

# Files Refract does not build: Linux processes, signals, threads, syscalls and exec memory are
# refract_native's (see src/), and guest<->host function wrappers are not used.
EXCLUDE = {
    'base/large_mmap.cc', 'base/maps_snapshot.cc', 'base/mapped_file_fragment.cc',
    'base/memfd_backed_mmap.cc', 'base/mmap_posix.cc', 'base/prctl_helpers.cc',
    'base/raw_syscall_x86_64.S', 'base/tracing.cc',
    'code_gen_lib/arm64_to_x86_64/gen_wrapper.cc',
    'interpreter/arm64/faulty_memory_accesses_x86_64.cc',
    'runtime/berberis.cc', 'runtime/execute_guest.cc', 'runtime/execute_guest_call.cc',
    'runtime/runtime_library.cc', 'runtime/runtime_library_x86_64.cc',
    'runtime/arm64/init_guest_arch.cc', 'runtime/arm64/run_guest_call.cc',
    # Translator glue (dispatch handlers, gear switching, entry stubs): src/runtime_win.cpp.
    'runtime/translator.cc', 'runtime/arm64/translator.cc', 'runtime/arm64/translator_x86_64.cc',
    'runtime_primitives/interpret_helpers_arm64.cc',
    'runtime_primitives/crash_reporter.cc', 'runtime_primitives/exec_region_anonymous.cc',
    'runtime_primitives/guest_code_region.cc', 'runtime_primitives/guest_function_wrapper_impl.cc',
    'runtime_primitives/host_function_wrapper_impl.cc',
    'runtime_primitives/known_guest_function_wrapper.cc', 'runtime_primitives/profiler_interface.cc',
    'runtime_primitives/signal_queue.cc', 'runtime_primitives/virtual_guest_call_frame.cc',
    'runtime_primitives/virtual_guest_call_frame_arm64.cc',
}
SKIP_MODULES = {'libberberis_guest_os_primitives_arm64', 'libberberis_kernel_api_arm64',
                'libberberis_instrument'}
DROP_DEFINES = {'ANDROID_STRICT', '__LIBC_API__', '__LIBM_API__', '__LIBDL_API__'}
BT = 'frameworks/libs/binary_translation/'
GEN = re.compile(r'^out/soong/\.intermediates/frameworks/libs/binary_translation/\S+/(\w+)/gen$')


def include_dir(path):
    if path.startswith('frameworks/') or path.startswith('external/fmtlib/'):
        return '${DIGITALIS_ROOT}/' + path
    m = GEN.match(path)
    if m:
        return '${DIGITALIS_GEN}/' + m.group(1)
    return None  # bionic, libc++, liblog, libbase: compat/ and MSVC's STL stand in


def main():
    data = json.load(open(sys.argv[1]))
    out = ['# Generated by tools/gen_modules_cmake.py from Soong; do not edit.', '']
    names = []
    for mod, objs in sorted(data['objs'].items()):
        if mod in SKIP_MODULES:
            continue
        srcs = [o['src'] for o in objs if o['src'][len(BT):] not in EXCLUDE]
        flags = data['vars'][mod]['cFlags1']
        incs, defs = ['${DIGITALIS_COMPAT}'], []
        for flag in re.findall(r'-I(\S+)|-D(\S+)', flags):
            if flag[0]:
                inc = include_dir(flag[0])
                if inc and inc not in incs:
                    incs.append(inc)
            elif flag[1].split('=')[0] not in DROP_DEFINES and flag[1] not in defs:
                defs.append(flag[1])
        target = 'dg_' + mod[len('libberberis_'):]
        # Include path and defines also for modules src/ replaces, so the port compiles like them.
        out.append(f'set({target}_INCLUDES')
        out += [f'  {i}' for i in incs]
        out.append(')')
        out.append(f'set({target}_DEFINES {" ".join(defs)})')
        if srcs:
            names.append(target)
            out.append(f'add_library({target} OBJECT')
            out += [f'  ${{DIGITALIS_ROOT}}/{s}' for s in srcs]
            out.append(')')
            out.append(f'target_include_directories({target} PRIVATE ${{{target}_INCLUDES}})')
            out.append(f'target_compile_definitions({target} PRIVATE ${{{target}_DEFINES}})')
            out.append(f'digitalis_module_options({target})')
        out.append('')
    out.append(f'set(DIGITALIS_MODULES {" ".join(names)})')
    open(sys.argv[2], 'w', newline='\n').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
